import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { OPERATOR_RESULT_RULES, TYPE_OPERATOR_RESULT_RULES } from '../src/analyzer/operator-rules.ts'
import { FUNCTION_SIGNATURES, type ResultRule } from '../src/analyzer/signatures.ts'
import { INFIX_PARSELETS, PREFIX_PARSELETS } from '../src/parser/precedence.ts'
import { R4_RESOURCES } from '../src/r4/generated/resources-data.ts'
import { R4_DATA_TYPES } from '../src/r4/generated/types-data.ts'
import { formatGeneratedTypeScript } from './format-generated.ts'

const outputUrl = new URL('../src/typed/generated/metadata.ts', import.meta.url)
const compactOutputUrl = new URL('../src/typed/generated/metadata-compact.ts', import.meta.url)
const MAX_FAST_RESOURCE_ROOT_LENGTH = 76
const MAX_FAST_ELEMENT_NAME_LENGTH = 33
const MAX_FAST_FUNCTION_NAME_LENGTH = 18

assertMaxLength(
  'R4 element',
  Object.values({ ...R4_DATA_TYPES, ...R4_RESOURCES }).flatMap(type => Object.keys(type.e)),
  MAX_FAST_ELEMENT_NAME_LENGTH
)
assertMaxLength(
  'R4 resource root',
  Object.keys(R4_RESOURCES).filter(name => !name.includes('.')),
  MAX_FAST_RESOURCE_ROOT_LENGTH
)
assertMaxLength('function', Object.keys(FUNCTION_SIGNATURES), MAX_FAST_FUNCTION_NAME_LENGTH)

function assertMaxLength(label: string, names: string[], limit: number): void {
  const oversized = names.filter(name => name.length > limit)
  if (oversized.length > 0) {
    throw new Error(`${label} names exceed the fast-parser source proof (${limit}): ${oversized.join(', ')}`)
  }
}

function generatedSource(): string {
  const functionRules = Object.fromEntries(
    Object.entries(FUNCTION_SIGNATURES)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, signature]) => [name, signature.result])
  )
  return `// Generated by scripts/generate-type-metadata.ts. Do not edit by hand.

export const TYPE_FUNCTION_RULES = ${JSON.stringify(functionRules, null, 2)} as const

export const TYPE_OPERATOR_RULES = ${JSON.stringify(OPERATOR_RESULT_RULES, null, 2)} as const

export const TYPE_TYPE_OPERATOR_RULES = ${JSON.stringify(TYPE_OPERATOR_RESULT_RULES, null, 2)} as const

export const TYPE_PREFIX_PARSELETS = ${JSON.stringify(PREFIX_PARSELETS, null, 2)} as const

export const TYPE_INFIX_PARSELETS = ${JSON.stringify(INFIX_PARSELETS, null, 2)} as const
`
}

function compactGeneratedSource(): string {
  return `// Generated by scripts/generate-type-metadata.ts. Do not edit by hand.

export interface CompactFunctionRules {
${Object.entries(FUNCTION_SIGNATURES)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, signature]) => `  ${JSON.stringify(name)}: ${compactResultRuleType(signature.result)}`)
  .join('\n')}
}

export interface CompactInfixParselets {
${Object.entries(INFIX_PARSELETS)
  .map(
    ([token, record]) =>
      `  ${JSON.stringify(token)}: readonly [${[
        record.tokenKind,
        record.fixity,
        record.bindingPower,
        record.associativity,
        record.rhs,
        record.reducer,
      ]
        .map(value => JSON.stringify(value))
        .join(', ')}]`
  )
  .join('\n')}
}
`
}

function compactResultRuleType(rule: ResultRule): string {
  switch (rule.kind) {
    case 'fixed':
      return `readonly ['fixed', ${rule.types?.map(type => JSON.stringify(type)).join(' | ') ?? 'never'}, ${rule.single ?? "'unknown'"}]`
    case 'input':
      return "readonly ['input']"
    case 'input-item':
      return "readonly ['input-item']"
    case 'argument':
      return `readonly ['argument', ${rule.index}, ${JSON.stringify(rule.cardinality)}]`
    case 'union':
      return `readonly ['union', ${rule.sources.map(source => JSON.stringify(source)).join(' | ')}, ${JSON.stringify(rule.single)}]`
    case 'arguments-union':
      return "readonly ['arguments-union']"
    case 'reference-targets':
      return "readonly ['reference-targets']"
    case 'unknown':
      return "readonly ['unknown']"
  }
}

const next = await formatGeneratedTypeScript(generatedSource())
const compactNext = await formatGeneratedTypeScript(compactGeneratedSource())
if (process.argv.includes('--check')) {
  for (const [url, expected] of [
    [outputUrl, next],
    [compactOutputUrl, compactNext],
  ] as const) {
    const path = fileURLToPath(url)
    if (readFileSync(path, 'utf8') !== expected) {
      console.error(`${path} is stale; run pnpm generate:type-metadata`)
      process.exitCode = 1
    }
  }
} else {
  writeFileSync(outputUrl, next)
  writeFileSync(compactOutputUrl, compactNext)
  console.log(`wrote ${fileURLToPath(outputUrl)}`)
  console.log(`wrote ${fileURLToPath(compactOutputUrl)}`)
}
